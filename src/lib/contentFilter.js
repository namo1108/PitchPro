// 팬 커뮤니티에 축구 얘기 대신 욕설/음란/혐오 표현이 섞이는 걸 막는 1차 방어선용 키워드 필터.
// 완벽하진 않다 - 새 은어·변형은 계속 생겨나고, "진짜 욕인지 인용/드립인지" 같은 문맥 판단은
// 단순 키워드 매칭으로 원천적으로 불가능하다. 명백한 단어만 걸러내고, 그 외(교묘한 비방, 정치
// 성향 논쟁 등)는 관리자(GOAT 계정)가 신고/발견 시 직접 지우는 걸로 보완한다.
const BLOCKED_WORDS = [
  // 욕설/비속어
  "시발", "씨발", "씨팔", "시팔", "개새끼", "개새키", "병신", "븅신", "지랄",
  "좆", "존나", "존니", "미친놈", "미친년", "썅", "개년", "걸레", "창녀", "잡놈", "개소리",
  "ㅅㅂ", "ㅄ", "ㅂㅅ", "ㅈㄴ", "ㄲㅈ",
  // 성적/음란 표현
  "야동", "포르노", "자위", "성기노출", "질내사정", "19금",
  // 혐오/차별 표현(정치·지역·인종 등을 겨냥한 멸칭 - "정치 얘기 자체"가 아니라 혐오성 표현만 대상)
  "틀딱", "한남충", "한녀충", "김치녀", "된장녀", "짱깨", "쪽바리", "좌빨", "우꼴", "빨갱이", "islam충",
];

// 띄어쓰기로 필터를 피하는 흔한 수법("시 발", "개  새 끼" 등)을 막기 위해 공백만 제거하고 비교한다.
function normalize(text) {
  return String(text || "").replace(/\s+/g, "");
}

export function findBlockedWord(text) {
  const normalized = normalize(text);
  return BLOCKED_WORDS.find((w) => normalized.includes(w)) || null;
}
